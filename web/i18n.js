const VALUE_MAPS = { en: VALUE_MAP_EN, ru: VALUE_MAP_RU, kk: VALUE_MAP_KK };

// ენუმ/ქალაქის მნიშვნელობას აქტიური ენისკენ თარგმნის (ka — უცვლელად)
function tval(value) {
    const lang = getLang();
    if (!value || lang === "ka") return value;
    const map = VALUE_MAPS[lang];
    if (!map) return value;
    if (map[value]) return map[value];
    const parts = String(value).split(/\s+/);
    if (parts.length > 1) {
        const mapped = parts.map((p) => map[p] || p);
        if (mapped.some((mw, i) => mw !== parts[i])) return mapped.join(" ");
    }
    return value;
}

